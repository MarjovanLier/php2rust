/// The first line of every output (P2R-52).
pub const HEADER: &str =
    "// Generated by php2rust. In release builds set overflow-checks = true, see the README.";

/// Why a conversion produced no Rust. Each string is the complete stderr text.
pub enum Failure {
    /// Exit 1: problem lines (P2R-03).
    Refused(String),
    /// Exit 2: the input is not valid PHP or the analyser could not finish (P2R-04).
    Invalid(String),
}

/// One input file: the path its problems print (P2R-03, P2R-171), the name Mago knows it
/// by, and its bytes.
pub struct Input {
    pub shown: String,
    pub name: String,
    pub source: Vec<u8>,
}

/// Converts one PHP file. `path` is the input path as given on the command line.
pub fn convert(path: &str, source: Vec<u8>) -> Result<String, Failure> {
    let input = Input {
        shown: path.to_owned(),
        name: path.to_owned(),
        source,
    };
    let mut written = analyse(vec![input], false)?;
    Ok(written.remove(0).1)
}

/// Converts the PHP files of a directory into the module files of one library crate, each
/// with its path inside the crate (P2R-170 to P2R-175).
pub fn convert_crate(inputs: Vec<Input>) -> Result<Vec<(String, String)>, Failure> {
    analyse(inputs, true)
}

/// Parses, analyses and converts the input files together: Mago scans every file into one
/// codebase, so a class of one file is known in the others (P2R-171). One file converts
/// to one output file; a `library` converts to the module files of a crate.
fn analyse(inputs: Vec<Input>, library: bool) -> Result<Vec<(String, String)>, Failure> {
    let shown: Vec<String> = inputs.iter().map(|input| input.shown.clone()).collect();
    let files: Vec<File> = inputs
        .into_iter()
        .map(|input| {
            File::ephemeral(
                Cow::Owned(input.name.into_bytes()),
                Cow::Owned(input.source),
            )
        })
        .collect();
    let named: Vec<(&str, &File)> = shown.iter().map(String::as_str).zip(&files).collect();
    let arena = LocalArena::new();
    let programs: Vec<&Program<'_>> = files.iter().map(|file| parse_file(&arena, file)).collect();
    // Mago recovers from broken input without failing, so its parse errors are checked here.
    let errors: Vec<Problem> = programs
        .iter()
        .flat_map(|program| program.errors.iter())
        .map(|error| spanned(error, Origin::Tool, format!("syntax error: {error}")))
        .collect();
    if !errors.is_empty() {
        return Err(Failure::Invalid(problem::render_files(&named, errors)));
    }
    let resolved: Vec<ResolvedNames<'_>> = programs
        .iter()
        .map(|program| NameResolver::new(&arena).resolve(program))
        .collect();
    let flats: Vec<Vec<Statement<'_>>> =
        programs.iter().map(|program| flattened(program)).collect();
    let mut codebase = Prelude::build().metadata;
    // An enum or class may not take the fully qualified name of a class-like PHP has built
    // in, and once the files are scanned the two cannot be told apart (P2R-111, P2R-131,
    // P2R-151).
    let mut built_in_classes: HashSet<Vec<u8>> = HashSet::new();
    // PHP rejects a function named like one it has built in; Mago does not. Inside a
    // namespace PHP accepts it, and the tool still refuses it (P2R-31, P2R-151).
    let mut built_in_functions: HashSet<Vec<u8>> = HashSet::new();
    for (statements, names) in flats.iter().zip(&resolved) {
        for statement in statements {
            match statement {
                Statement::Enum(Enum { name, .. })
                | Statement::Class(Class { name, .. })
                | Statement::Trait(Trait { name, .. }) => {
                    let full = names.resolve(name).unwrap_or(name.value);
                    if codebase.get_class_like(full).is_some() {
                        built_in_classes.insert(full.to_ascii_lowercase());
                    }
                }
                Statement::Function(function)
                    if codebase.get_function(function.name.value).is_some() =>
                {
                    built_in_functions.insert(function.name.value.to_ascii_lowercase());
                }
                _ => {}
            }
        }
    }
    for ((file, program), names) in files.iter().zip(&programs).zip(&resolved) {
        codebase.extend(scan_program(
            &arena,
            file,
            program,
            names,
            PHPVersion::PHP85,
        ));
    }
    populate_codebase(
        &mut codebase,
        &mut SymbolReferences::new(),
        Default::default(),
        Default::default(),
    );
    let plugins = PluginRegistry::new();
    let mut problems: Vec<Problem> = Vec::new();
    let mut analysed: Vec<Analysed<'_>> = Vec::new();
    for (((file, program), names), path) in files.iter().zip(&programs).zip(&resolved).zip(&shown) {
        let analyzer = Analyzer::new(
            &arena,
            file,
            names,
            &codebase,
            &plugins,
            Settings::new(PHPVersion::PHP85),
        );
        let mut result = AnalysisResult::new(SymbolReferences::new());
        let Ok(artifacts) = analyzer.analyze_with_artifacts(program, &mut result) else {
            return Err(Failure::Invalid(format!(
                "{path}: the Mago analyser could not finish\n"
            )));
        };
        // The declaration Mago names in a duplicate depends on how the path is written, so
        // the tool reports duplicates itself (P2R-173).
        problems.extend(
            result
                .issues
                .iter()
                .filter(|issue| reported(issue))
                .filter(|issue| !library || issue.code.as_deref() != Some("duplicate-definition"))
                .filter_map(mago_problem),
        );
        analysed.push(Analysed {
            file: file.id,
            source: file,
            resolved: names,
            artifacts,
        });
    }
    let units: Vec<Program<'_>> = flats
        .iter()
        .zip(&programs)
        .map(|(statements, program)| Program {
            statements: Sequence { nodes: statements },
            ..(*program).clone()
        })
        .collect();
    let mut converter = Converter::new(&codebase, analysed);
    converter.built_in_classes = built_in_classes;
    converter.built_in_functions = built_in_functions;
    converter.library = library;
    let written = converter.program(&units);
    problems.append(&mut converter.problems);
    if problems.is_empty() {
        Ok(written)
    } else {
        Err(Failure::Refused(problem::render_files(&named, problems)))
    }
}

/// The top-level statements with those of an unbraced namespace lifted out of it, as PHP
/// runs them. The namespace stays in front of them with an empty body, so its place can be
/// checked; a braced namespace stays whole and is refused (P2R-150).
fn flattened<'a>(program: &Program<'a>) -> Vec<Statement<'a>> {
    let mut statements = Vec::new();
    for statement in program.statements.iter() {
        match statement {
            Statement::Namespace(namespace) => match &namespace.body {
                NamespaceBody::Implicit(body) => {
                    statements.push(Statement::Namespace(Namespace {
                        body: NamespaceBody::Implicit(NamespaceImplicitBody {
                            terminator: body.terminator,
                            statements: Sequence::empty(),
                        }),
                        ..namespace.clone()
                    }));
                    statements.extend(body.statements.iter().cloned());
                }
                NamespaceBody::BraceDelimited(_) => statements.push(statement.clone()),
            },
            other => statements.push(other.clone()),
        }
    }
    statements
}

/// The last segment of a fully qualified name.
fn short_name(key: &[u8]) -> &[u8] {
    key.rsplit(|byte| *byte == b'\\').next().unwrap_or(key)
}

/// Mago findings that refuse the conversion (P2R-11).
fn reported(issue: &Issue) -> bool {
    issue.level == Level::Error || issue.code.as_deref() == Some("possibly-undefined-variable")
}

fn mago_problem(issue: &Issue) -> Option<Problem> {
    let span = issue
        .annotations
        .iter()
        .find(|a| a.kind == AnnotationKind::Primary)?
        .span;
    let code = issue.code.as_deref().unwrap_or("mago");
    Some(Problem {
        file: span.file_id,
        start: span.start.offset,
        end: span.end.offset,
        origin: Origin::Mago,
        message: format!("{} ({code})", issue.message),
    })
}

fn spanned(node: &impl HasSpan, origin: Origin, message: String) -> Problem {
    let span = node.span();
    Problem {
        file: span.file_id,
        start: span.start.offset,
        end: span.end.offset,
        origin,
        message,
    }
}

/// True for exactly `declare(strict_types=1);` (P2R-12).
fn is_strict_types(declare: &Declare<'_>) -> bool {
    let mut items = declare.items.iter();
    let (Some(item), None) = (items.next(), items.next()) else {
        return false;
    };
    item.name.value.eq_ignore_ascii_case(b"strict_types")
        && matches!(
            item.value,
            Expression::Literal(Literal::Integer(LiteralInteger { value: Some(1), .. }))
        )
        && matches!(declare.body, DeclareBody::Statement(Statement::Noop(_)))
}

/// The output file: the header, then each item after one blank line, `fn main()` last.
fn assemble(mut items: Vec<Vec<String>>, main: Vec<String>) -> String {
    if !main.is_empty() {
        let mut lines = vec!["fn main() {".to_owned()];
        lines.extend(main);
        lines.push("}".to_owned());
        items.push(lines);
    }
    let mut out = format!("{HEADER}\n");
    for item in items {
        out.push('\n');
        for line in item {
            out.push_str(&line);
            out.push('\n');
        }
    }
    out
}

/// A short name for a statement in problem messages.
fn statement_kind(statement: &Statement<'_>) -> &'static str {
    match statement {
        Statement::Namespace(_) => "namespace",
        Statement::Use(_) => "use",
        Statement::Class(_) => "a class",
        Statement::Interface(_) => "an interface",
        Statement::Trait(_) => "a trait",
        Statement::Enum(_) => "an enum",
        Statement::Constant(_) => "const",
        Statement::Function(_) => "a function declared inside another statement",
        Statement::Global(_) => "global",
        Statement::Static(_) => "a static variable",
        Statement::Unset(_) => "unset",
        Statement::Switch(_) => "switch",
        Statement::Try(_) => "try",
        Statement::If(_) => "if",
        Statement::While(_) => "while",
        Statement::DoWhile(_) => "do-while",
        Statement::For(_) => "for",
        Statement::Foreach(_) => "foreach",
        Statement::Block(_) => "a block",
        Statement::Return(_) => "return",
        Statement::Expression(_) => "this expression statement",
        _ => "this statement",
    }
}

/// A function declared in the file, as Rust sees it.
#[derive(Clone)]
struct Signature {
    rust_name: String,
    parameters: Vec<ParameterSignature>,
    returns: Option<RustType>,
    /// True when it returns a `Result` because it throws (P2R-211).
    throws: bool,
}

impl Signature {
    /// The ` -> R` of its Rust signature, empty for `void`; a function that throws returns
    /// `Result<R, PhpException>` (P2R-211).
    fn returns_text(&self) -> String {
        let returns = self.returns.as_ref().map(RustType::owned);
        match (self.throws, returns) {
            (true, returns) => format!(
                " -> Result<{}, PhpException>",
                returns.as_deref().unwrap_or("()")
            ),
            (false, Some(returns)) => format!(" -> {returns}"),
            (false, None) => String::new(),
        }
    }
}

#[derive(Clone)]
struct ParameterSignature {
    /// The PHP name without `$`.
    php_name: Vec<u8>,
    rust_name: String,
    /// The snake_case name without `r#`, for the `_` prefix of an unused parameter.
    snake: String,
    ty: RustType,
    mode: Mode,
    /// The default value, converted at the declaration, with its Rust type (P2R-168).
    default: Option<(RExpr, RustType)>,
}

/// The parameter a written argument of a call goes to: a positional one to the parameter
/// at its position, a named one to the parameter of its name, which PHP matches with its
/// letter case (P2R-169). `None` for a spread argument or a name no parameter has.
fn parameter_index(
    position: usize,
    argument: &Argument<'_>,
    parameters: &[ParameterSignature],
) -> Option<usize> {
    match argument {
        Argument::Positional(_) if argument.is_unpacked() => None,
        Argument::Positional(_) => Some(position),
        Argument::Named(named) => parameters
            .iter()
            .position(|parameter| parameter.php_name == named.name.value),
    }
}

/// How a parameter of a changing type takes its argument; any other parameter is
/// `Shared` (P2R-143).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Mode {
    /// `&C`, `&str`, `&[T]`, or a Copy value.
    Shared,
    /// `&mut C` or `&mut [C]`.
    Mut,
    /// `C` or `Vec<C>`, which the body moves.
    Owned,
}

impl Mode {
    /// The Rust type of a parameter of type `ty` in this mode.
    fn parameter(self, ty: &RustType) -> String {
        match (self, ty) {
            (Mode::Shared, ty) => ty.parameter(),
            (Mode::Mut, RustType::Vec(element)) => format!("&mut [{}]", element.owned()),
            (Mode::Mut, ty) => format!("&mut {}", ty.owned()),
            (Mode::Owned, ty) => ty.owned(),
        }
    }
}

/// Where a statement sits: `fn main()`, or a function with this return type.
#[derive(Clone, Copy)]
enum Context<'t> {
    Main,
    Function(Option<&'t RustType>),
}

/// What Mago found in one input file. Both maps are keyed by offsets only, so a lookup
/// takes the file of its node (P2R-171).
struct Analysed<'c> {
    file: FileId,
    /// The file itself, which names the metadata of its closures (P2R-300).
    source: &'c File,
    /// The fully qualified name of each name in the file, as PHP resolves it (P2R-151).
    resolved: &'c ResolvedNames<'c>,
    /// The type Mago found for each expression, keyed by its span (P2R-21).
    artifacts: AnalysisArtifacts,
}

struct Converter<'c> {
    codebase: &'c CodebaseMetadata,
    /// The input files as Mago analysed them.
    files: Vec<Analysed<'c>>,
    problems: Vec<Problem>,
    /// Declared functions by lowercase PHP name, because PHP function names ignore case (P2R-32).
    functions: HashMap<Vec<u8>, Signature>,
    /// The enums of the file in source order (P2R-110).
    enums: Vec<enums::EnumInfo>,
    /// The Rust type of each enum and class by lowercase PHP name (P2R-111, P2R-131).
    type_names: TypeNames,
    /// The readonly classes of the file in source order (P2R-130).
    classes: Vec<classes::ClassInfo>,
    /// The class and method whose body is converting, by index (P2R-135).
    current_method: Option<(usize, usize)>,
    /// The class or enum whose body is converting, which `self` and `static` name
    /// (P2R-153, P2R-156).
    current_class: Option<usize>,
    /// The key of the function whose body is converting (P2R-151).
    current_function: Option<Vec<u8>>,
    /// The calls of that body that call the function or method itself (P2R-50, P2R-135).
    self_calls: Vec<Span>,
    /// The lowercase names of the file's enums and classes that PHP already has as a
    /// class-like (P2R-111, P2R-131).
    built_in_classes: HashSet<Vec<u8>>,
    /// The lowercase names of the file's functions that PHP already has (P2R-31).
    built_in_functions: HashSet<Vec<u8>>,
    /// The spans of the `default` arm results left out of the output (P2R-121).
    dropped_defaults: Vec<Span>,
    /// The foreach loops that iterate by `&mut` or over a copy (P2R-146).
    loops: modes::Loops,
    /// The variables of the body being converted: a function, or `fn main()`.
    variables: Variables,
    /// The helpers each module calls, by module index (P2R-160, P2R-172).
    helpers: BTreeSet<(usize, helpers::Helper)>,
    /// True for a directory input, which converts to a library crate (P2R-175).
    library: bool,
    /// The module whose items are converting (P2R-172).
    current_module: usize,
    /// The path of each module below the crate root, in Rust names; the root's is empty
    /// and comes first. One input file has only the root (P2R-172).
    module_paths: Vec<Vec<String>>,
    /// Where the error of a call that throws goes here; `None` inside a closure the output
    /// writes, where it cannot go anywhere (P2R-213).
    raise: Option<printer::Raise>,
    /// The flow blocks of the `throw`s and calls that throw so far in the body of the `try`
    /// that is converting, which lead to its handlers (P2R-214).
    attempt: Option<Vec<usize>>,
    /// True while the body of a function that throws converts (P2R-211).
    throwing: bool,
    /// The number of `try` statements around the statement converting (P2R-214).
    trying: usize,
    /// True once a `throw` converts, so the output holds the exception struct (P2R-210).
    uses_exceptions: bool,
    /// The variables of the open `catch` clauses: PHP name with `$`, Rust name, and
    /// whether a handler read it (P2R-214).
    caught: Vec<(Vec<u8>, String, bool)>,
    /// The PHP name, with `$`, of the variable that `is_scalar()` checks in the condition
    /// of the `?:` whose first arm is converting, while that arm is `(string)` of it
    /// (P2R-233).
    scalar_guard: Option<Vec<u8>>,
    /// The key orders, by PHP key, of the array literals that build each shape struct
    /// (P2R-271).
    shape_orders: BTreeMap<String, BTreeSet<Vec<Vec<u8>>>>,
    /// The places that turn a value of a shape struct into a map, with its struct (P2R-271).
    shape_maps: Vec<(Span, String)>,
    /// The innermost statement converting, whose earlier reads of a variable a move in it
    /// must not break (P2R-26).
    statement: Option<Span>,
    /// The keys of the traits a class or enum of the input uses (P2R-280).
    used_traits: HashSet<Vec<u8>>,
}

impl<'c> Converter<'c> {
    fn new(codebase: &'c CodebaseMetadata, files: Vec<Analysed<'c>>) -> Self {
        Self {
            codebase,
            files,
            problems: Vec::new(),
            functions: HashMap::new(),
            enums: Vec::new(),
            type_names: TypeNames::default(),
            classes: Vec::new(),
            current_method: None,
            current_class: None,
            current_function: None,
            self_calls: Vec::new(),
            built_in_classes: HashSet::new(),
            built_in_functions: HashSet::new(),
            dropped_defaults: Vec::new(),
            loops: modes::Loops::default(),
            variables: Variables::default(),
            helpers: BTreeSet::new(),
            library: false,
            current_module: 0,
            module_paths: vec![Vec::new()],
            // Statements outside functions are `fn main()` (P2R-213).
            raise: Some(printer::Raise::Abort),
            attempt: None,
            throwing: false,
            trying: 0,
            uses_exceptions: false,
            caught: Vec::new(),
            scalar_guard: None,
            shape_orders: BTreeMap::new(),
            shape_maps: Vec::new(),
            statement: None,
            used_traits: HashSet::new(),
        }
    }

    /// What Mago found in the file of `node`.
    fn analysed(&self, node: &impl HasSpan) -> &Analysed<'c> {
        let file = node.span().file_id;
        self.files
            .iter()
            .find(|analysed| analysed.file == file)
            .expect("every node comes from an input file")
    }

    /// The type Mago found for the expression `node` (P2R-21).
    fn expression_type(&self, node: &impl HasSpan) -> Option<&TUnion> {
        self.analysed(node).artifacts.get_expression_type(node)
    }

    /// The lowercase fully qualified name of the name at `node`, written `raw`: PHP class
    /// and function names ignore letter case (P2R-32, P2R-111, P2R-151).
    fn name_key(&self, node: &impl HasSpan, raw: &[u8]) -> Vec<u8> {
        let full = self
            .analysed(node)
            .resolved
            .resolve(&node.span().start)
            .unwrap_or(raw);
        full.strip_prefix(b"\\")
            .unwrap_or(full)
            .to_ascii_lowercase()
    }

    /// The key of a declared function: its fully qualified name (P2R-151).
    fn function_key(&self, function: &Function<'_>) -> Vec<u8> {
        self.name_key(&function.name, function.name.value)
    }

    /// The key of the class, enum or function a name in a use refers to, as PHP resolves
    /// it from the namespace and the `use` lines (P2R-151).
    fn identifier_key(&self, identifier: &Identifier<'_>) -> Vec<u8> {
        self.name_key(identifier, identifier.value())
    }

    /// The key of the class or enum a class name in a use refers to: a name, or `self` and
    /// `static` inside the body of a class or enum, where `static` is `self` because no
    /// class extends another (P2R-153). `None` for `parent` or an expression.
    fn class_key(&self, class: &Expression<'_>) -> Option<Vec<u8>> {
        match class {
            Expression::Identifier(identifier) => Some(self.identifier_key(identifier)),
            Expression::Self_(_) | Expression::Static(_) => {
                Some(self.classes[self.current_class?].key.clone())
            }
            _ => None,
        }
    }

    /// True for a call of the built-in function `name` (lowercase): by its name in any
    /// letter case, with or without a leading `\`, or by an unqualified name inside a
    /// namespace that no import maps, where PHP falls back to the global function
    /// (P2R-32, P2R-151).
    fn calls_built_in(&self, call: &FunctionCall<'_>, name: &[u8]) -> bool {
        let Expression::Identifier(identifier) = call.function else {
            return false;
        };
        self.names_built_in(identifier, name)
    }

    /// True when `identifier` names the built-in function `name`, as for a call
    /// (P2R-32, P2R-151).
    fn names_built_in(&self, identifier: &Identifier<'_>, name: &[u8]) -> bool {
        let key = self.identifier_key(identifier);
        !self.functions.contains_key(&key)
            && (key == name || (self.falls_back(identifier) && short_name(&key) == name))
    }

    /// True for an unqualified name that no import maps, which PHP looks up in the global
    /// namespace when the current namespace has no function of that name (P2R-151).
    fn falls_back(&self, identifier: &Identifier<'_>) -> bool {
        matches!(identifier, Identifier::Local(_))
            && !self
                .analysed(identifier)
                .resolved
                .is_imported(&identifier.span().start)
    }

    /// The key of the function a call by `identifier` runs: its fully qualified name, or,
    /// for an unqualified name in a namespace whose namespaced name no function of the
    /// crate has, the crate's function of that name in the global namespace (P2R-171).
    fn call_key(&self, identifier: &Identifier<'_>) -> Vec<u8> {
        let key = self.identifier_key(identifier);
        if self.functions.contains_key(&key) || !self.falls_back(identifier) {
            return key;
        }
        let global = short_name(&key).to_vec();
        if self.functions.contains_key(&global) {
            global
        } else {
            key
        }
    }

    fn refuse(&mut self, node: &impl HasSpan, message: impl Into<String>) {
        self.problems
            .push(spanned(node, Origin::Tool, message.into()));
    }

    /// Converts the input files: one file to its output file, or the files of a directory
    /// to the module files of a crate, each with its path in the crate (P2R-33, P2R-172).
    /// Every file registers before any body converts, so a body can use the enums,
    /// classes and functions of every file (P2R-171).
    fn program(&mut self, units: &[Program<'_>]) -> Vec<(String, String)> {
        for unit in units {
            self.check_uses(unit.statements.as_slice());
        }
        let module_of = self.modules(units);
        let statements: Vec<Statement<'_>> = units
            .iter()
            .flat_map(|unit| unit.statements.iter().cloned())
            .collect();
        let program = Program {
            statements: Sequence { nodes: &statements },
            ..units[0].clone()
        };
        if self.library {
            self.duplicates(units, &module_of);
        }
        self.register_enums(&program);
        self.register_class_names(&program);
        self.register(&program);
        self.register_class_members(&program);
        self.decide_throws(&program);
        self.decide_modes(&program);
        for (span, message) in std::mem::take(&mut self.loops.problems) {
            self.refuse(&span, message);
        }
        let sites = self.site_types(program.statements.iter(), None);
        self.variables.list_types = sites.lists;
        self.variables.null_types = sites.nulls;
        let mut items: Vec<Vec<Vec<String>>> = vec![Vec::new(); self.module_paths.len()];
        // The module of each enum, class and function, by Rust name (P2R-174).
        let mut owners: BTreeMap<String, (usize, crates::ItemKind)> = BTreeMap::new();
        let mut main: Vec<String> = Vec::new();
        // Each enum's place among the items, filled once every use is known (P2R-115).
        let mut enum_slots: Vec<(usize, usize, usize, &Enum<'_>)> = Vec::new();
        for (unit, &module) in units.iter().zip(&module_of) {
            self.current_module = module;
            let items = &mut items[module];
            let mut declared = false;
            let mut started = false;
            // A statement of `fn main()` has run, so a later enum is not declared yet
            // (P2R-110).
            let mut ran = false;
            let mut after_closing_tag = false;
            for statement in unit.statements.iter() {
                match statement {
                    Statement::OpeningTag(_) | Statement::ClosingTag(_) | Statement::Noop(_) => {}
                    // PHP drops the one newline right after a closing tag, so it is not
                    // output text.
                    Statement::Inline(inline)
                        if after_closing_tag && matches!(inline.value, b"\n" | b"\r\n") => {}
                    Statement::Inline(inline) => {
                        self.refuse(inline, "text outside PHP tags is not supported (P2R-13)")
                    }
                    Statement::Declare(declare)
                        if !declared && !started && is_strict_types(declare) =>
                    {
                        declared = true
                    }
                    // The statements of an unbraced namespace follow it at the top level
                    // (P2R-150).
                    Statement::Namespace(namespace)
                        if declared
                            && !started
                            && matches!(namespace.body, NamespaceBody::Implicit(_)) =>
                    {
                        started = true
                    }
                    other => {
                        if !declared && !started {
                            self.refuse(
                                other,
                                "the file must start with declare(strict_types=1); (P2R-12)",
                            );
                        }
                        started = true;
                        match other {
                            // Without the declare, that problem is the one reported.
                            Statement::Namespace(_) if !declared => {}
                            Statement::Namespace(_) => self.refuse(
                                other,
                                "a file may hold one namespace statement, without braces, right after the declare (P2R-150)",
                            ),
                            // A `use` only changes how names resolve (P2R-150).
                            Statement::Use(_) => {}
                            Statement::Function(function) => {
                                if let Some(item) = self.function(function) {
                                    let name = self.functions[&self.function_key(function)]
                                        .rust_name
                                        .clone();
                                    owners.insert(name, (module, crates::ItemKind::Function));
                                    items.push(item);
                                }
                            }
                            Statement::Enum(declaration) => {
                                if ran {
                                    self.refuse(
                                        &declaration.name,
                                        "an enum must come before the statements outside functions, because PHP declares it only when execution reaches it (P2R-110)",
                                    );
                                }
                                if let Some(index) = self.enum_index(declaration) {
                                    let name = self.enums[index].rust_name.clone();
                                    owners.insert(name, (module, crates::ItemKind::Type));
                                    items.push(Vec::new());
                                    enum_slots.push((module, items.len() - 1, index, declaration));
                                }
                            }
                            // PHP declares a readonly class before any statement runs, so it
                            // may come after them (P2R-130).
                            Statement::Class(declaration) => {
                                // PHP declares a class with interfaces or traits only when
                                // execution reaches it, as it declares an enum.
                                let late = declaration.implements.is_some()
                                    || declaration
                                        .members
                                        .iter()
                                        .any(|m| matches!(m, ClassLikeMember::TraitUse(_)));
                                if ran && late {
                                    self.refuse(
                                        &declaration.name,
                                        "a class that implements an interface or uses a trait must come before the statements outside functions, because PHP declares it only when execution reaches it (P2R-130, P2R-280)",
                                    );
                                }
                                if let Some(index) = self.class_index(declaration) {
                                    let name = self.classes[index].rust_name.clone();
                                    owners.insert(name, (module, crates::ItemKind::Type));
                                    let item = self.class_item(declaration, index);
                                    items.push(item);
                                }
                            }
                            // Its constants go into each class that uses it (P2R-280).
                            Statement::Trait(declaration) => self.check_trait(declaration),
                            _ if self.library => self.refuse(
                                other,
                                "a directory converts to a library, which has no statements outside functions (P2R-175)",
                            ),
                            _ => {
                                ran = true;
                                self.statement(other, 1, Context::Main, &mut main)
                            }
                        }
                    }
                }
                after_closing_tag = matches!(statement, Statement::ClosingTag(_));
            }
            if !declared && !started {
                self.problems.push(Problem {
                    file: unit.file_id,
                    start: 0,
                    end: 0,
                    origin: Origin::Tool,
                    message: "the file must start with declare(strict_types=1); (P2R-12)".into(),
                });
            }
        }
        self.finish_variables(&mut main);
        // Every enum method converts before any enum is written, because a method can use
        // the helpers of any enum (P2R-115, P2R-155).
        let methods: Vec<Vec<Vec<String>>> = enum_slots
            .iter()
            .map(|&(module, _, _, declaration)| {
                self.current_module = module;
                self.enum_methods(declaration)
            })
            .collect();
        for ((module, slot, index, _), methods) in enum_slots.into_iter().zip(methods) {
            items[module][slot] = self.enum_item(index, methods);
        }
        // Every body has converted, so every array shape the output uses is known; their
        // structs come first, in the crate root for a directory (P2R-200, P2R-172).
        self.check_shape_maps();
        let mut shapes = self.shape_items();
        // The union enums follow the shape structs, in the same place (P2R-230).
        shapes.extend(self.union_items());
        // The struct of `DateTime` follows them, also where only a helper names it
        // (P2R-330).
        let date_time = (
            crate::types::DATE_TIME.to_owned(),
            helpers::date_time_lines(),
        );
        shapes.push(date_time.clone());
        let mut shapes = shapes::named(shapes, &items, &main);
        if self
            .helpers
            .iter()
            .any(|(_, helper)| helper.names_date_time())
            && !shapes.contains(&date_time)
        {
            shapes.push(date_time);
        }
        // The exception struct follows the shapes in the crate root, and the items of one
        // file (P2R-210).
        let exception = self.uses_exceptions.then(throws::exception_lines);
        if self.library {
            let mut root = Vec::new();
            for (name, lines) in shapes {
                owners.insert(name, (0, crates::ItemKind::Type));
                root.push(lines);
            }
            if let Some(lines) = exception {
                owners.insert("PhpException".to_owned(), (0, crates::ItemKind::Type));
                root.push(lines);
            }
            items[0].splice(0..0, root);
            return self.crate_files(items, &owners);
        }
        // Every body has converted, so every helper call is known (P2R-160).
        let mut items = items.remove(0);
        items.splice(0..0, shapes.into_iter().map(|(_, lines)| lines));
        items.extend(exception);
        items.extend(self.helpers.iter().map(|(_, helper)| helper.lines()));
        let text = items
            .iter()
            .chain([&main])
            .flatten()
            .cloned()
            .collect::<Vec<_>>();
        if crates::names_index_map(&text.join("\n")) {
            items.insert(0, vec![crates::INDEX_MAP_USE.to_owned()]);
        }
        vec![(String::new(), assemble(items, main))]
    }
}
