/// The first line of every output (P2R-52).
pub const HEADER: &str =
    "// Generated by php2rust. In release builds set overflow-checks = true, see the README.";

/// Why a conversion produced no Rust. Each string is the complete stderr text.
pub enum Failure {
    /// Exit 1: problem lines (P2R-03).
    Refused(String),
    /// Exit 2: the input is not valid PHP or the analyser could not finish (P2R-04).
    Invalid(String),
}

/// Converts one PHP file. `path` is the input path as given on the command line.
pub fn convert(path: &str, source: Vec<u8>) -> Result<String, Failure> {
    let file = File::ephemeral(Cow::Owned(path.as_bytes().to_vec()), Cow::Owned(source));
    let arena = LocalArena::new();
    let program = parse_file(&arena, &file);
    // Mago recovers from broken input without failing, so its parse errors are checked here.
    if program.has_errors() {
        let errors = program
            .errors
            .iter()
            .map(|error| spanned(error, Origin::Tool, format!("syntax error: {error}")))
            .collect();
        return Err(Failure::Invalid(problem::render(path, &file, errors)));
    }
    let resolved = NameResolver::new(&arena).resolve(program);
    let statements = flattened(program);
    let flat = Program {
        statements: Sequence { nodes: &statements },
        ..program.clone()
    };
    let mut codebase = Prelude::build().metadata;
    // An enum or class may not take the fully qualified name of a class-like PHP has built
    // in, and once the file is scanned the two cannot be told apart (P2R-111, P2R-131,
    // P2R-151).
    let built_in_classes: HashSet<Vec<u8>> = statements
        .iter()
        .filter_map(|statement| {
            let name = match statement {
                Statement::Enum(declaration) => &declaration.name,
                Statement::Class(declaration) => &declaration.name,
                _ => return None,
            };
            let full = resolved.resolve(name).unwrap_or(name.value);
            codebase
                .get_class_like(full)
                .is_some()
                .then(|| full.to_ascii_lowercase())
        })
        .collect();
    // PHP rejects a function named like one it has built in; Mago does not. Inside a
    // namespace PHP accepts it, and the tool still refuses it (P2R-31, P2R-151).
    let built_in_functions: HashSet<Vec<u8>> = statements
        .iter()
        .filter_map(|statement| match statement {
            Statement::Function(function)
                if codebase.get_function(function.name.value).is_some() =>
            {
                Some(function.name.value.to_ascii_lowercase())
            }
            _ => None,
        })
        .collect();
    codebase.extend(scan_program(
        &arena,
        &file,
        program,
        &resolved,
        PHPVersion::PHP85,
    ));
    populate_codebase(
        &mut codebase,
        &mut SymbolReferences::new(),
        Default::default(),
        Default::default(),
    );
    let plugins = PluginRegistry::new();
    let analyzer = Analyzer::new(
        &arena,
        &file,
        &resolved,
        &codebase,
        &plugins,
        Settings::new(PHPVersion::PHP85),
    );
    let mut result = AnalysisResult::new(SymbolReferences::new());
    let Ok(artifacts) = analyzer.analyze_with_artifacts(program, &mut result) else {
        return Err(Failure::Invalid(format!(
            "{path}: the Mago analyser could not finish\n"
        )));
    };
    let mut problems: Vec<Problem> = result
        .issues
        .iter()
        .filter(|issue| reported(issue))
        .filter_map(mago_problem)
        .collect();
    let mut converter = Converter::new(&codebase, &resolved, artifacts);
    converter.built_in_classes = built_in_classes;
    converter.built_in_functions = built_in_functions;
    let rust = converter.program(&flat);
    problems.append(&mut converter.problems);
    if problems.is_empty() {
        Ok(rust)
    } else {
        Err(Failure::Refused(problem::render(path, &file, problems)))
    }
}

/// The top-level statements with those of an unbraced namespace lifted out of it, as PHP
/// runs them. The namespace stays in front of them with an empty body, so its place can be
/// checked; a braced namespace stays whole and is refused (P2R-150).
fn flattened<'a>(program: &Program<'a>) -> Vec<Statement<'a>> {
    let mut statements = Vec::new();
    for statement in program.statements.iter() {
        match statement {
            Statement::Namespace(namespace) => match &namespace.body {
                NamespaceBody::Implicit(body) => {
                    statements.push(Statement::Namespace(Namespace {
                        body: NamespaceBody::Implicit(NamespaceImplicitBody {
                            terminator: body.terminator,
                            statements: Sequence::empty(),
                        }),
                        ..namespace.clone()
                    }));
                    statements.extend(body.statements.iter().cloned());
                }
                NamespaceBody::BraceDelimited(_) => statements.push(statement.clone()),
            },
            other => statements.push(other.clone()),
        }
    }
    statements
}

/// Mago findings that refuse the conversion (P2R-11).
fn reported(issue: &Issue) -> bool {
    issue.level == Level::Error || issue.code.as_deref() == Some("possibly-undefined-variable")
}

fn mago_problem(issue: &Issue) -> Option<Problem> {
    let span = issue
        .annotations
        .iter()
        .find(|a| a.kind == AnnotationKind::Primary)?
        .span;
    let code = issue.code.as_deref().unwrap_or("mago");
    Some(Problem {
        start: span.start.offset,
        end: span.end.offset,
        origin: Origin::Mago,
        message: format!("{} ({code})", issue.message),
    })
}

fn spanned(node: &impl HasSpan, origin: Origin, message: String) -> Problem {
    let span = node.span();
    Problem {
        start: span.start.offset,
        end: span.end.offset,
        origin,
        message,
    }
}

/// True for exactly `declare(strict_types=1);` (P2R-12).
fn is_strict_types(declare: &Declare<'_>) -> bool {
    let mut items = declare.items.iter();
    let (Some(item), None) = (items.next(), items.next()) else {
        return false;
    };
    item.name.value.eq_ignore_ascii_case(b"strict_types")
        && matches!(
            item.value,
            Expression::Literal(Literal::Integer(LiteralInteger { value: Some(1), .. }))
        )
        && matches!(declare.body, DeclareBody::Statement(Statement::Noop(_)))
}

/// The output file: the header, then each item after one blank line, `fn main()` last.
fn assemble(mut items: Vec<Vec<String>>, main: Vec<String>) -> String {
    if !main.is_empty() {
        let mut lines = vec!["fn main() {".to_owned()];
        lines.extend(main);
        lines.push("}".to_owned());
        items.push(lines);
    }
    let mut out = format!("{HEADER}\n");
    for item in items {
        out.push('\n');
        for line in item {
            out.push_str(&line);
            out.push('\n');
        }
    }
    out
}

/// A short name for a statement in problem messages.
fn statement_kind(statement: &Statement<'_>) -> &'static str {
    match statement {
        Statement::Namespace(_) => "namespace",
        Statement::Use(_) => "use",
        Statement::Class(_) => "a class",
        Statement::Interface(_) => "an interface",
        Statement::Trait(_) => "a trait",
        Statement::Enum(_) => "an enum",
        Statement::Constant(_) => "const",
        Statement::Function(_) => "a function declared inside another statement",
        Statement::Global(_) => "global",
        Statement::Static(_) => "a static variable",
        Statement::Unset(_) => "unset",
        Statement::Switch(_) => "switch",
        Statement::Try(_) => "try",
        Statement::If(_) => "if",
        Statement::While(_) => "while",
        Statement::DoWhile(_) => "do-while",
        Statement::For(_) => "for",
        Statement::Foreach(_) => "foreach",
        Statement::Block(_) => "a block",
        Statement::Return(_) => "return",
        Statement::Expression(_) => "this expression statement",
        _ => "this statement",
    }
}

/// A function declared in the file, as Rust sees it.
#[derive(Clone)]
struct Signature {
    rust_name: String,
    parameters: Vec<ParameterSignature>,
    returns: Option<RustType>,
}

#[derive(Clone)]
struct ParameterSignature {
    /// The PHP name without `$`.
    php_name: Vec<u8>,
    rust_name: String,
    /// The snake_case name without `r#`, for the `_` prefix of an unused parameter.
    snake: String,
    ty: RustType,
    mode: Mode,
}

/// How a parameter of a changing type takes its argument; any other parameter is
/// `Shared` (P2R-143).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Mode {
    /// `&C`, `&str`, `&[T]`, or a Copy value.
    Shared,
    /// `&mut C` or `&mut [C]`.
    Mut,
    /// `C` or `Vec<C>`, which the body moves.
    Owned,
}

impl Mode {
    /// The Rust type of a parameter of type `ty` in this mode.
    fn parameter(self, ty: &RustType) -> String {
        match (self, ty) {
            (Mode::Shared, ty) => ty.parameter(),
            (Mode::Mut, RustType::Vec(element)) => format!("&mut [{}]", element.owned()),
            (Mode::Mut, ty) => format!("&mut {}", ty.owned()),
            (Mode::Owned, ty) => ty.owned(),
        }
    }
}

/// Where a statement sits: `fn main()`, or a function with this return type.
#[derive(Clone, Copy)]
enum Context<'t> {
    Main,
    Function(Option<&'t RustType>),
}

struct Converter<'c> {
    codebase: &'c CodebaseMetadata,
    /// The fully qualified name of each name in the file, as PHP resolves it (P2R-151).
    resolved: &'c ResolvedNames<'c>,
    /// The type Mago found for each expression, keyed by its span (P2R-21).
    artifacts: AnalysisArtifacts,
    problems: Vec<Problem>,
    /// Declared functions by lowercase PHP name, because PHP function names ignore case (P2R-32).
    functions: HashMap<Vec<u8>, Signature>,
    /// The enums of the file in source order (P2R-110).
    enums: Vec<enums::EnumInfo>,
    /// The Rust type of each enum and class by lowercase PHP name (P2R-111, P2R-131).
    type_names: TypeNames,
    /// The readonly classes of the file in source order (P2R-130).
    classes: Vec<classes::ClassInfo>,
    /// The class and method whose body is converting, by index (P2R-135).
    current_method: Option<(usize, usize)>,
    /// The class or enum whose body is converting, which `self` and `static` name
    /// (P2R-153, P2R-156).
    current_class: Option<usize>,
    /// The key of the function whose body is converting (P2R-151).
    current_function: Option<Vec<u8>>,
    /// The calls of that body that call the function or method itself (P2R-50, P2R-135).
    self_calls: Vec<Span>,
    /// The lowercase names of the file's enums and classes that PHP already has as a
    /// class-like (P2R-111, P2R-131).
    built_in_classes: HashSet<Vec<u8>>,
    /// The lowercase names of the file's functions that PHP already has (P2R-31).
    built_in_functions: HashSet<Vec<u8>>,
    /// The spans of the `default` arm results left out of the output (P2R-121).
    dropped_defaults: Vec<Span>,
    /// The foreach loops that iterate by `&mut` or over a copy (P2R-146).
    loops: modes::Loops,
    /// The variables of the body being converted: a function, or `fn main()`.
    variables: Variables,
}

impl<'c> Converter<'c> {
    fn new(
        codebase: &'c CodebaseMetadata,
        resolved: &'c ResolvedNames<'c>,
        artifacts: AnalysisArtifacts,
    ) -> Self {
        Self {
            codebase,
            resolved,
            artifacts,
            problems: Vec::new(),
            functions: HashMap::new(),
            enums: Vec::new(),
            type_names: TypeNames::new(),
            classes: Vec::new(),
            current_method: None,
            current_class: None,
            current_function: None,
            self_calls: Vec::new(),
            built_in_classes: HashSet::new(),
            built_in_functions: HashSet::new(),
            dropped_defaults: Vec::new(),
            loops: modes::Loops::default(),
            variables: Variables::default(),
        }
    }

    /// The lowercase fully qualified name of the name at `node`, written `raw`: PHP class
    /// and function names ignore letter case (P2R-32, P2R-111, P2R-151).
    fn name_key(&self, node: &impl HasSpan, raw: &[u8]) -> Vec<u8> {
        let full = self.resolved.resolve(&node.span().start).unwrap_or(raw);
        full.strip_prefix(b"\\")
            .unwrap_or(full)
            .to_ascii_lowercase()
    }

    /// The key of a declared function: its fully qualified name (P2R-151).
    fn function_key(&self, function: &Function<'_>) -> Vec<u8> {
        self.name_key(&function.name, function.name.value)
    }

    /// The key of the class, enum or function a name in a use refers to, as PHP resolves
    /// it from the namespace and the `use` lines (P2R-151).
    fn identifier_key(&self, identifier: &Identifier<'_>) -> Vec<u8> {
        self.name_key(identifier, identifier.value())
    }

    /// The key of the class or enum a class name in a use refers to: a name, or `self` and
    /// `static` inside the body of a class or enum, where `static` is `self` because no
    /// class extends another (P2R-153). `None` for `parent` or an expression.
    fn class_key(&self, class: &Expression<'_>) -> Option<Vec<u8>> {
        match class {
            Expression::Identifier(identifier) => Some(self.identifier_key(identifier)),
            Expression::Self_(_) | Expression::Static(_) => {
                Some(self.classes[self.current_class?].key.clone())
            }
            _ => None,
        }
    }

    /// True for a call of the built-in function `name` (lowercase): by its name in any
    /// letter case, with or without a leading `\`, or by an unqualified name inside a
    /// namespace that no import maps, where PHP falls back to the global function
    /// (P2R-32, P2R-151).
    fn calls_built_in(&self, call: &FunctionCall<'_>, name: &[u8]) -> bool {
        let Expression::Identifier(identifier) = call.function else {
            return false;
        };
        let key = self.identifier_key(identifier);
        let falls_back = matches!(identifier, Identifier::Local(_))
            && !self.resolved.is_imported(&identifier.span().start);
        !self.functions.contains_key(&key)
            && (key == name || (falls_back && key.rsplit(|b| *b == b'\\').next() == Some(name)))
    }

    fn refuse(&mut self, node: &impl HasSpan, message: impl Into<String>) {
        self.problems
            .push(spanned(node, Origin::Tool, message.into()));
    }

    /// One output line at `depth` levels of indentation, refused when rustfmt would split
    /// it (P2R-51). A line that holds a copy mark is measured at the end of the body.
    fn emit(&mut self, node: &impl HasSpan, depth: usize, text: String) -> String {
        let line = format!("{}{text}", "    ".repeat(depth));
        if line.len() > printer::MAX_WIDTH && !line.contains(variables::COPY) {
            self.refuse(node, "this statement is too long for one line (P2R-51)");
        }
        line
    }

    /// Lays out an expression on one line, refused when rustfmt would split it (P2R-51).
    fn render(&mut self, node: &impl HasSpan, expr: &RExpr, anchor: bool) -> Option<String> {
        match printer::expr(expr, anchor) {
            Ok(text) => Some(text),
            Err(TooWide) => {
                self.refuse(node, "this statement is too long for one line (P2R-51)");
                None
            }
        }
    }

    fn program(&mut self, program: &Program<'_>) -> String {
        self.check_uses(program.statements.as_slice());
        self.register_enums(program);
        self.register_class_names(program);
        self.register(program);
        self.register_class_members(program);
        self.decide_modes(program);
        for (span, message) in std::mem::take(&mut self.loops.problems) {
            self.refuse(&span, message);
        }
        let sites = self.site_types(program.statements.iter(), None);
        self.variables.list_types = sites.lists;
        self.variables.null_types = sites.nulls;
        let mut items: Vec<Vec<String>> = Vec::new();
        let mut main: Vec<String> = Vec::new();
        // Each enum's place among the items, filled once every use is known (P2R-115).
        let mut enum_slots: Vec<(usize, usize, &Enum<'_>)> = Vec::new();
        let mut declared = false;
        let mut started = false;
        // A statement of `fn main()` has run, so a later enum is not declared yet (P2R-110).
        let mut ran = false;
        let mut after_closing_tag = false;
        for statement in program.statements.iter() {
            match statement {
                Statement::OpeningTag(_) | Statement::ClosingTag(_) | Statement::Noop(_) => {}
                // PHP drops the one newline right after a closing tag, so it is not output text.
                Statement::Inline(inline)
                    if after_closing_tag && matches!(inline.value, b"\n" | b"\r\n") => {}
                Statement::Inline(inline) => {
                    self.refuse(inline, "text outside PHP tags is not supported (P2R-13)")
                }
                Statement::Declare(declare)
                    if !declared && !started && is_strict_types(declare) =>
                {
                    declared = true
                }
                // The statements of an unbraced namespace follow it at the top level
                // (P2R-150).
                Statement::Namespace(namespace)
                    if declared
                        && !started
                        && matches!(namespace.body, NamespaceBody::Implicit(_)) =>
                {
                    started = true
                }
                other => {
                    if !declared && !started {
                        self.refuse(
                            other,
                            "the file must start with declare(strict_types=1); (P2R-12)",
                        );
                    }
                    started = true;
                    match other {
                        // Without the declare, that problem is the one reported.
                        Statement::Namespace(_) if !declared => {}
                        Statement::Namespace(_) => self.refuse(
                            other,
                            "a file may hold one namespace statement, without braces, right after the declare (P2R-150)",
                        ),
                        // A `use` only changes how names resolve (P2R-150).
                        Statement::Use(_) => {}
                        Statement::Function(function) => {
                            if let Some(item) = self.function(function) {
                                items.push(item);
                            }
                        }
                        Statement::Enum(declaration) => {
                            if ran {
                                self.refuse(
                                    &declaration.name,
                                    "an enum must come before the statements outside functions, because PHP declares it only when execution reaches it (P2R-110)",
                                );
                            }
                            if let Some(index) = self.enum_index(declaration) {
                                items.push(Vec::new());
                                enum_slots.push((items.len() - 1, index, declaration));
                            }
                        }
                        // PHP declares a readonly class before any statement runs, so it may
                        // come after them (P2R-130).
                        Statement::Class(declaration) => {
                            if let Some(index) = self.class_index(declaration) {
                                let item = self.class_item(declaration, index);
                                items.push(item);
                            }
                        }
                        _ => {
                            ran = true;
                            self.statement(other, 1, Context::Main, &mut main)
                        }
                    }
                }
            }
            after_closing_tag = matches!(statement, Statement::ClosingTag(_));
        }
        if !declared && !started {
            self.problems.push(Problem {
                start: 0,
                end: 0,
                origin: Origin::Tool,
                message: "the file must start with declare(strict_types=1); (P2R-12)".into(),
            });
        }
        self.finish_variables(&mut main);
        // Every enum method converts before any enum is written, because a method can use
        // the helpers of any enum (P2R-115, P2R-155).
        let methods: Vec<Vec<Vec<String>>> = enum_slots
            .iter()
            .map(|(_, _, declaration)| self.enum_methods(declaration))
            .collect();
        for ((slot, index, _), methods) in enum_slots.into_iter().zip(methods) {
            items[slot] = self.enum_item(index, methods);
        }
        assemble(items, main)
    }
}
